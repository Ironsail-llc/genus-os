"use client";

import { createContext, useContext, useCallback, useState } from "react";
import React from "react";

export interface ViewEntry {
  toolName: string;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  props: Record<string, any>;
  title: string;
}

export interface DashboardRequest {
  intent: string;
  data?: Record<string, unknown>;
}

export interface RenderRequest {
  component: string;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  props: Record<string, any>;
}

export interface CanvasUpdateRequest {
  messages: Array<{ role: string; content: string }>;
  agentData?: Record<string, unknown> | null;
}

export type CanvasMode = "idle" | "loading" | "native" | "dashboard" | "error";

/** An action request from a dashboard button/form. */
export interface ActionRequest {
  tool: string;
  params: Record<string, unknown>;
  /** Unique ID for tracking the action lifecycle */
  id: string;
}

export interface ActionResult {
  id: string;
  success: boolean;
  data?: unknown;
  error?: string;
}

interface VisualStateContextType {
  // Legacy view stack (for native component rendering)
  viewStack: ViewEntry[];
  currentView: ViewEntry | null;
  pushView: (view: ViewEntry) => void;
  popView: () => void;
  clearViews: () => void;

  // Dashboard subagent
  dashboardRequest: DashboardRequest | null;
  setDashboard: (req: DashboardRequest) => void;
  clearDashboard: () => void;

  // Direct render from markers
  renderRequest: RenderRequest | null;
  setRender: (req: RenderRequest) => void;

  // Canvas mode
  canvasMode: CanvasMode;
  setCanvasMode: (mode: CanvasMode) => void;

  // Dashboard code (generated by subagent)
  dashboardCode: string | null;
  dashboardCodeType: "tsx" | "html" | null;
  setDashboardCode: (code: string, type: "tsx" | "html") => void;
  clearDashboardCode: () => void;

  // Background update indicator
  isUpdating: boolean;
  setIsUpdating: (v: boolean) => void;

  // Conversation-driven dashboard update (new v2 flow)
  pendingMessages: Array<{ role: string; content: string }> | null;
  pendingAgentData: Record<string, unknown> | null;
  notifyConversationUpdate: (messages: Array<{ role: string; content: string }>, agentData?: Record<string, unknown>) => void;
  /** Which turn `pendingMessages` is: it counts up with every notify. */
  pendingTurn: number;
  /** True for the first canvas to claim `turn`, false for every later one. */
  claimTurn: (turn: number) => boolean;
  /** A claimer that left before finishing gives `turn` back for another canvas. */
  releaseTurn: (turn: number) => void;
  /** Counts releases, so the canvases still mounted look at the turn again. */
  turnReleases: number;
  /** The last canvas update's failure, shown on every canvas (any one may have asked). */
  canvasError: string | null;
  setCanvasError: (error: string | null) => void;
  /** The last canvas update asked for, so any canvas can retry it. */
  canvasRequests: {
    last: () => CanvasUpdateRequest | null;
    remember: (request: CanvasUpdateRequest) => void;
  };

  // Canvas actions (Phase 4)
  pendingAction: ActionRequest | null;
  lastActionResult: ActionResult | null;
  submitAction: (action: ActionRequest) => void;
  resolveAction: (result: ActionResult) => void;
}

const VisualStateContext = createContext<VisualStateContextType | null>(null);

export function VisualStateProvider({
  children,
}: {
  children: React.ReactNode;
}) {
  const [viewStack, setViewStack] = useState<ViewEntry[]>([]);
  const [dashboardRequest, setDashboardRequest] =
    useState<DashboardRequest | null>(null);
  const [renderRequest, setRenderRequest] = useState<RenderRequest | null>(
    null
  );
  const [canvasMode, setCanvasMode] = useState<CanvasMode>("idle");
  const [dashboardCode, setDashboardCodeState] = useState<string | null>(null);
  const [dashboardCodeType, setDashboardCodeType] = useState<
    "tsx" | "html" | null
  >(null);
  const [isUpdating, setIsUpdating] = useState(false);
  const [pendingMessages, setPendingMessages] = useState<
    Array<{ role: string; content: string }> | null
  >(null);
  const [pendingAgentData, setPendingAgentData] = useState<
    Record<string, unknown> | null
  >(null);
  const [pendingTurn, setPendingTurn] = useState(0);

  // Phase 4: Canvas actions
  const [pendingAction, setPendingAction] = useState<ActionRequest | null>(null);
  const [lastActionResult, setLastActionResult] = useState<ActionResult | null>(null);

  const submitAction = useCallback((action: ActionRequest) => {
    setPendingAction(action);
    setLastActionResult(null);
  }, []);

  const resolveAction = useCallback((result: ActionResult) => {
    setLastActionResult(result);
    setPendingAction(null);
  }, []);

  const pushView = useCallback((view: ViewEntry) => {
    setViewStack((prev) => [...prev, view]);
    setCanvasMode("native");
    setDashboardRequest(null);
    setRenderRequest(null);
  }, []);

  const popView = useCallback(() => {
    setViewStack((prev) => {
      const next = prev.slice(0, -1);
      if (next.length === 0) {
        setCanvasMode("idle");
      }
      return next;
    });
  }, []);

  const clearViews = useCallback(() => {
    setViewStack([]);
    setCanvasMode("idle");
  }, []);

  const setDashboard = useCallback((req: DashboardRequest) => {
    setDashboardRequest(req);
    setCanvasMode("loading");
    setViewStack([]);
    setRenderRequest(null);
  }, []);

  const clearDashboard = useCallback(() => {
    setDashboardRequest(null);
    setCanvasMode("idle");
  }, []);

  const setRender = useCallback(
    (req: RenderRequest) => {
      setRenderRequest(req);
      // Push as a view entry for the native renderer
      pushView({
        toolName: req.component,
        props: req.props,
        title: req.component.replace(/^render_/, "").replace(/_/g, " "),
      });
    },
    [pushView]
  );

  const setDashboardCode = useCallback(
    (code: string, type: "tsx" | "html") => {
      setDashboardCodeState(code);
      setDashboardCodeType(type);
      setCanvasMode("dashboard");
    },
    []
  );

  const clearDashboardCode = useCallback(() => {
    setDashboardCodeState(null);
    setDashboardCodeType(null);
  }, []);

  // Announces a conversation turn. It does NOT raise `isUpdating`: that flag
  // drives the canvas spinner and is cleared only by `useDashboardAgent`, so
  // only the agent may raise it, and only around a request it actually has in
  // flight.
  //
  // Behaviour change (home is the real-data dashboard now): the AI canvas —
  // and with it `useDashboardAgent` — mounts only when the operator asks for
  // it, so a chat reply no longer regenerates a canvas while that view is
  // closed. Raising the flag here regardless, as this used to, latched it on
  // forever with nobody left to clear it: the canvas then opened onto a
  // permanent "Updating" spinner for work nobody was doing.
  const notifyConversationUpdate = useCallback(
    (messages: Array<{ role: string; content: string }>, agentData?: Record<string, unknown>) => {
      setPendingMessages(messages);
      setPendingAgentData(agentData && Object.keys(agentData).length > 0 ? agentData : null);
      setPendingTurn((turn) => turn + 1);
    },
    []
  );

  // Each mounted canvas (the chat's rail, the dashboard's AI canvas) runs its
  // own dashboard agent, and their results land in this one shared slot. The
  // first to claim a turn generates it; the rest would pay for a second
  // triage+generate pipeline whose answer overwrites the first.
  //
  // A claimer that unmounts mid-request releases its turn, and the release
  // re-renders, so a canvas still mounted (or the next to mount) generates it
  // instead of the turn being lost. The failure and the request to retry live
  // here, beside `dashboardCode`, because the claimer is often a canvas the
  // operator cannot see (the dashboard view stays mounted while hidden).
  const [turnReleases, setTurnReleases] = useState(0);
  const [canvasError, setCanvasError] = useState<string | null>(null);
  // Created once per provider; claiming a turn must not re-render anything.
  const [turns] = useState(() => {
    let claimed = 0;
    return {
      claim: (turn: number) => {
        if (turn <= claimed) return false;
        claimed = turn;
        return true;
      },
      release: (turn: number) => {
        if (claimed !== turn) return false;
        claimed = turn - 1;
        return true;
      },
    };
  });
  const claimTurn = turns.claim;
  const releaseTurn = useCallback(
    (turn: number) => {
      if (turns.release(turn)) setTurnReleases((n) => n + 1);
    },
    [turns],
  );
  const [canvasRequests] = useState(() => {
    let last: CanvasUpdateRequest | null = null;
    return {
      last: () => last,
      remember: (request: CanvasUpdateRequest) => {
        last = request;
      },
    };
  });

  const currentView =
    viewStack.length > 0 ? viewStack[viewStack.length - 1] : null;

  return React.createElement(
    VisualStateContext.Provider,
    {
      value: {
        viewStack,
        currentView,
        pushView,
        popView,
        clearViews,
        dashboardRequest,
        setDashboard,
        clearDashboard,
        renderRequest,
        setRender,
        canvasMode,
        setCanvasMode,
        dashboardCode,
        dashboardCodeType,
        setDashboardCode,
        clearDashboardCode,
        isUpdating,
        setIsUpdating,
        pendingMessages,
        pendingAgentData,
        notifyConversationUpdate,
        pendingTurn,
        claimTurn,
        releaseTurn,
        turnReleases,
        canvasError,
        setCanvasError,
        canvasRequests,
        pendingAction,
        lastActionResult,
        submitAction,
        resolveAction,
      },
    },
    children
  );
}

export function useVisualState() {
  const context = useContext(VisualStateContext);
  if (!context) {
    throw new Error("useVisualState must be used within VisualStateProvider");
  }
  return context;
}
