"""``genus init`` — the command, and the pieces of it the wizard borrows.

This module is the ORCHESTRATOR. It turns flags and the environment into an
:class:`robothor.init.context.InitContext`, asks the chosen substrate for its
plan, runs the two phases and owns the exit code. Every decision the wizard
makes lives in :mod:`robothor.init`.

It also keeps the handful of helpers that predate the package and are still
the single implementation of what they do -- ``create_workspace``,
``check_prerequisites``, the ``.robothor/init_state.yaml`` reader and writer,
the Ollama puller, the Docker infrastructure generator -- because the steps
call them, and two copies of "create a workspace" is how a scaffold silently
stops shipping half its files.

Usage:
    genus init                     # interactive
    genus init --yes               # non-interactive; defaults and environment
    genus init --yes --json        # one document on stdout, humans on stderr
    genus init --dry-run           # print the plan, write nothing
"""

