def _provider_key_from_env() -> str:
    """The credential for the provider whose key this box already carries.

    Read straight from the process environment rather than through the settings
    model on purpose: provider keys are secrets, they are not settings, and the
    only thing this value is ever used for is one probe call.
    """
    from robothor.engine.key_pool import PROVIDERS

    for spec in PROVIDERS:
        value = os.environ.get(spec.env_var, "").strip()
        if value:
            return value
    return ""


def build_init_context(args: Any) -> Any:
    """Turn parsed flags and the environment into an :class:`InitContext`.

    Every answer the wizard could need is seeded here, which is what lets
    ``--yes`` run without a terminal: ``ctx.ask`` only prompts for what it was
    not given.
    """
    from robothor.init.context import InitContext

    workspace = Path(getattr(args, "workspace", None) or Path.home() / "robothor")

    answers: dict[str, Any] = {}
    for key, attribute in _ANSWER_FLAGS.items():
        value = getattr(args, attribute, None)
        if value not in (None, "", False):
            answers[key] = value
    for key, variable in _ANSWER_ENV.items():
        if key in answers:
            continue
        value = os.environ.get(variable, "").strip()
        if value:
            answers[key] = value
    key = _provider_key_from_env()
    if key:
        answers["provider_key"] = key

    return InitContext(
        workspace=workspace,
        answers=answers,
        dry_run=bool(getattr(args, "dry_run", False)),
        json_mode=bool(getattr(args, "json", False)),
        yes=bool(getattr(args, "yes", False)),
        offline=bool(getattr(args, "offline", False)),
        substrate_name=str(
            getattr(args, "substrate", None) or os.environ.get("ROBOTHOR_INIT_SUBSTRATE") or "local"
        ),
    )


def run_init(args: Any) -> int:
    """Two-phase orchestrator for the first-run wizard.

    Phase 1 checks everything and prints the plan. Phase 2 applies it, one
    resumable step at a time. The steps themselves live in ``robothor.init``;
    this function owns the flags, the streams and the exit code, and nothing
    else -- which is why ``genus init --json`` can put one document on stdout
    without a single step knowing about it.
    """
    from robothor.init.plan import run_plan
    from robothor.init.render import (
        render_json,
        render_outcome,
        render_plan,
        render_summary,
    )
    from robothor.init.substrate import build_plan

    ctx = build_init_context(args)
    ctx.say("")
    ctx.say("  Genus OS Setup")
    ctx.say("  " + "=" * 14)
    ctx.say("")

    try:
        plan = build_plan(ctx)
    except (NotImplementedError, ValueError) as exc:
        # A substrate that is designed but not built, or one that does not
        # exist. Both are the operator's command, not the operator's machine,
        # so neither is a plan row -- there is no plan to put it in.
        ctx.say(f"  --substrate {ctx.substrate_name}: {exc}")
        return 1

    width = max((len(step.id) for step in plan.steps), default=0)
    applying = False

    def show_plan(entries: Any) -> None:
        nonlocal applying
        for line in render_plan(entries, plan.substrate_name):
            ctx.say(line)
        if not any(row.status == "blocked" for row in entries):
            ctx.say("")
            ctx.say("  Dry run:" if ctx.dry_run else "  Applying:")
            applying = True

    def show_step(outcome: Any) -> None:
        if applying:
            ctx.say(render_outcome(outcome, width))

    result = run_plan(ctx, plan, on_plan=show_plan, on_step=show_step)

    for line in render_summary(result, workspace=str(ctx.workspace)):
        ctx.say(line)
    if getattr(args, "json", False):
        print(render_json(result))
    return int(result.exit_code)


def check_prerequisites(
    *,
    docker_required: bool = False,
    required: Sequence[str] = (),
) -> list[dict[str, Any]]:
    """Check for required and optional tools.

    Returns a list of dicts: {name, found, detail, required, hint}.

    ``required`` names the tools THIS substrate cannot run without, by the
    ``name`` field below. Every prerequisite used to be optional on every
    install, which is why a box with no PostgreSQL passed this check and then
    failed at the migration, four steps and one operator identity later.
    Python stays required unconditionally; nothing runs without it.
    """
    wanted = set(required)

    def _required(name: str, *, always: bool = False) -> bool:
        return always or name in wanted

    results = []

    # Python (always present)
    results.append(
        {
            "name": "Python",
            "found": True,
            "detail": f"{sys.version.split()[0]}",
            "required": True,
            "hint": "",
        }
    )

    # psql
    psql = shutil.which("psql")
    results.append(
        {
            "name": "PostgreSQL (psql)",
            "found": psql is not None,
            "detail": "found" if psql else "not found",
            "required": _required("PostgreSQL (psql)"),
            "hint": _install_hint("postgresql-client", "postgresql"),
        }
    )

    # redis-cli
    redis_cli = shutil.which("redis-cli")
    results.append(
        {
            "name": "Redis (redis-cli)",
            "found": redis_cli is not None,
            "detail": "found" if redis_cli else "not found",
            "required": _required("Redis (redis-cli)"),
            "hint": _install_hint("redis-server", "redis"),
        }
    )

    # Ollama
    ollama_found = False
    ollama_detail = "not reachable"
    try:
        base_url = os.environ.get("ROBOTHOR_OLLAMA_HOST", "127.0.0.1")
        port = os.environ.get("ROBOTHOR_OLLAMA_PORT", "11434")
        resp = httpx.get(f"http://{base_url}:{port}/api/tags", timeout=3)
        resp.raise_for_status()
        models = resp.json().get("models", [])
        ollama_found = True
        ollama_detail = f"{len(models)} model(s) loaded"
    except Exception:
        ollama_detail = "not reachable"
    results.append(
        {
            "name": "Ollama",
            "found": ollama_found,
            "detail": ollama_detail,
            "required": _required("Ollama"),
            "hint": "curl -fsSL https://ollama.com/install.sh | sh",
        }
    )

    # Docker (required only with --docker)
    docker_bin = shutil.which("docker")
    results.append(
        {
            "name": "Docker",
            "found": docker_bin is not None,
            "detail": "found" if docker_bin else "not found",
            "required": _required("Docker", always=docker_required),
            "hint": "https://docs.docker.com/engine/install/",
        }
    )

    return results


