def resolve_workspace_templates(
    workspace: Path,
    *,
    ai_name: str = "",
    ai_email: str = "",
    owner_name: str = "",
    owner_email: str = "",
) -> list[Path]:
    """Replace the scaffold's ``{{placeholders}}``. Returns what it rewrote.

    Extracted from the old ``run_init`` body so the wizard's workspace step can
    call it and a test can assert on it. Idempotent: a file with no ``{{`` left
    in it is not rewritten, so a re-run cannot undo an operator's edits.
    """
    replacements = {
        "{{ai_name}}": ai_name,
        "{{owner_name}}": owner_name,
        "{{ai_email}}": ai_email,
        "{{owner_email}}": owner_email,
    }
    rewritten: list[Path] = []
    for relative in TEMPLATED_FILES:
        path = workspace / relative
        if not path.exists():
            continue
        content = path.read_text()
        if "{{" not in content:
            continue
        for token, value in replacements.items():
            content = content.replace(token, value)
        path.write_text(content)
        rewritten.append(path)
    return rewritten


def write_workspace_pointer(workspace: Path) -> Path | None:
    """Write the one value ``config.yaml`` structurally cannot hold.

    ``.robothor/config.yaml`` lives INSIDE the workspace, so it cannot tell a
    process where the workspace is; that has to come from the environment. This
    writes a two-line ``.env`` carrying ``ROBOTHOR_WORKSPACE`` and nothing else,
    for anything that sources it.

    Everything else the old sixteen-line ``.env`` held -- the database, Redis,
    Ollama, the AI name, the timezone -- is now written through the settings
    writer into ``config.yaml``, by the step that owns it. Holding a value in
    two files means a later ``genus config set`` changes one of them, the
    environment silently wins, and the command reports "applied" while the
    service reads the old number.

    Never overwrites: an operator who has edited this file keeps their edit.
    Returns the path when it wrote one, else None.
    """
    path = workspace / ".env"
    if path.exists():
        return None
    path.write_text(
        "# Written by `genus init`. Everything else this instance configures\n"
        "# lives in .robothor/config.yaml -- `genus config get|set` reads and\n"
        "# writes it. This file carries only the pointer to the workspace,\n"
        "# which config.yaml cannot hold because it lives inside it.\n"
        f"ROBOTHOR_WORKSPACE={workspace}\n",
        encoding="utf-8",
    )
    return path


def _find_template_dir(package_dir: Path | None = None) -> Path | None:
    """Locate the init scaffold templates/ directory.

    Resolution order:

    1. ``ROBOTHOR_TEMPLATE_DIR`` — explicit operator override. When set it is
       authoritative: a bad value returns ``None`` rather than silently
       falling back to a different scaffold.
    2. Repo-root ``templates/`` when running from a checkout. Detected by
       walking the package directory's ancestors for a repo marker
       (``pyproject.toml`` + ``templates/`` + the ``robothor`` package), not
       by parent-count arithmetic.
    3. The scaffold bundled into the wheel at
       ``robothor/templates/bundled_scaffold`` (see the force-include in
       pyproject.toml).

    The bare code-package dir (``robothor/templates/`` itself) is never
    returned — it contains Python modules, not the scaffold.
    """
    env_dir = os.environ.get("ROBOTHOR_TEMPLATE_DIR")
    if env_dir:
        env_path = Path(env_dir)
        if env_path.is_dir():
            return env_path
        print(f"  Warning: ROBOTHOR_TEMPLATE_DIR={env_dir} is not a directory")
        return None

    if package_dir is None:
        package_dir = Path(__file__).resolve().parent
    else:
        package_dir = package_dir.resolve()

    # Checkout layout: the repo root is the ancestor that has the project
    # marker files. Covers both `/repo/robothor/` and a venv nested inside
    # the repo (`/repo/venv/.../site-packages/robothor/`).
    for ancestor in package_dir.parents:
        if (
            (ancestor / "pyproject.toml").is_file()
            and (ancestor / "templates").is_dir()
            and (ancestor / "robothor" / "__init__.py").is_file()
        ):
            return ancestor / "templates"

    # Wheel layout: the scaffold ships as package data.
    bundled = package_dir / "templates" / "bundled_scaffold"
    if bundled.is_dir():
        return bundled
    if package_dir == Path(__file__).resolve().parent:
        # Fall back to importlib.resources for exotic install layouts.
        try:
            from importlib import resources

            resource_dir = Path(str(resources.files("robothor"))) / "templates"
            bundled = resource_dir / "bundled_scaffold"
            if bundled.is_dir():
                return bundled
        except Exception:  # pragma: no cover - defensive
            pass
    return None


def _detect_install_mode() -> str:
    """Return ``"checkout"`` or ``"wheel"`` for the running install.

    Reuses ``_find_template_dir()`` (the #245 scaffold-resolution helper)
    rather than re-deriving the checkout/wheel distinction: a checkout
    resolves to the repo-root ``templates/`` directory, a wheel install
    resolves to the bundled ``.../robothor/templates/bundled_scaffold``. If
    neither can be resolved, default to "wheel" — the more conservative
    guidance (no systemd assumptions).
    """
    template_dir = _find_template_dir()
    if template_dir is not None and template_dir.name != "bundled_scaffold":
        return "checkout"
    return "wheel"


def helm_port() -> int:
    """The port the Helm dashboard serves the wizard on.

    Read from the settings model so an instance that moved the dashboard gets a
    link that works. A config.yaml that does not parse falls back to the
    declared default rather than stopping init: this is the command an operator
    runs to fix such a box.
    """
    try:
        from robothor.settings import get_settings

        return int(get_settings().services.helm_port)
    except Exception:  # noqa: BLE001 - a broken config must not block first run
        return 3004


def pull_ollama_models(base_url: str, models: list[str]) -> None:
    """Pull required Ollama models with progress output."""
    for model in models:
        print(f"  Pulling {model} ...", end=" ", flush=True)
        try:
            with httpx.stream(
                "POST",
                f"{base_url}/api/pull",
                json={"name": model},
                timeout=httpx.Timeout(5.0, read=600.0),
            ) as resp:
                resp.raise_for_status()
                last_status = ""
                for line in resp.iter_lines():
                    if not line:
                        continue
                    try:
                        data = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    status = data.get("status", "")
                    if status != last_status:
                        last_status = status
                print("done")
        except Exception as e:
            print(f"failed ({e})")


def write_env_file(
    path: Path,
    db: DatabaseConfig,
    redis: RedisConfig,
    ollama: OllamaConfig,
    *,
    owner_name: str = "",
    ai_name: str = "Robothor",
    owner_email: str = "",
    ai_email: str = "",
    timezone: str = "America/New_York",
    profiles: list[str] | None = None,
    yes: bool = False,
) -> bool:
    """Write .env file with configuration. Returns True if written."""
    if path.exists() and not yes:
        overwrite = input(f"  {path} exists. Overwrite? [y/N]: ").strip().lower()
        if overwrite != "y":
            print(f"  Keeping existing {path}")
            return False

    # Extract non-secret config values — secrets are NEVER written to .env
    db_host = str(db.host)
    db_port = str(db.port)
    db_name = str(db.name)
    db_user = str(db.user)
    # Operator identity is NOT written here: ROBOTHOR_OWNER_NAME and
    # ROBOTHOR_OWNER_EMAIL are deprecated in favour of ~/.robothor/owner.yaml,
    # which run_init writes through robothor.owner_config.write_owner_config.
    # Two files claiming the same identity is how an instance ends up
    # answering to one name and filing CRM rows under another.
    lines = [
        f"ROBOTHOR_AI_NAME={ai_name}",
        f"ROBOTHOR_AI_EMAIL={ai_email}",
        f"ROBOTHOR_TIMEZONE={timezone}",
        f"ROBOTHOR_DB_HOST={db_host}",
        f"ROBOTHOR_DB_PORT={db_port}",
        f"ROBOTHOR_DB_NAME={db_name}",
        f"ROBOTHOR_DB_USER={db_user}",
        "# ROBOTHOR_DB_PASSWORD — set via SOPS secrets or env, not stored here",
        "ROBOTHOR_DB_PASSWORD=",
        f"ROBOTHOR_REDIS_HOST={redis.host}",
        f"ROBOTHOR_REDIS_PORT={redis.port}",
        f"ROBOTHOR_OLLAMA_HOST={ollama.host}",
        f"ROBOTHOR_OLLAMA_PORT={ollama.port}",
        f"ROBOTHOR_WORKSPACE={path.parent}",
    ]
    if profiles:
        lines.append(f"COMPOSE_PROFILES={','.join(profiles)}")
    path.write_text("\n".join(lines) + "\n")
    return True


